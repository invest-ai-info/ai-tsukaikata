"""事業所得/雑所得の判定ラベルと留保の有無を文字列照合で数える（記事公開前の下ごしらえ用）。"""
import re

HEDGE_PHRASES = [
    "一つに決めることはできません",
    "どちらとも言える",
    "どちらとも言えます",
]

CAVEAT_PHRASES = [
    "可能性があります",
    "可能性も十分にあります",
    "可能性も残ります",
    "改善が必要",
    "確認することをおすすめします",
    "判断が変わる可能性があります",
]


def verdict(text: str) -> str:
    stripped = text.strip()
    if stripped in ("雑所得", "事業所得"):
        return stripped
    if any(p in text for p in HEDGE_PHRASES):
        return "要確認"
    # 「事業所得」「雑所得」のうち、決定的な言い方（です／と考えられます／と判断します／と判断できます）
    # が直後に続く方を見出しの結論として採用する。
    biz = re.search(r"事業所得(です|と考えられます|と判断します|と判断できます)", text)
    misc = re.search(r"雑所得(です|と考えられます|と判断します|と判断できます)", text)
    if biz and not misc:
        return "事業所得"
    if misc and not biz:
        return "雑所得"
    if biz and misc:
        return f"両方言及（位置: 事業所得={biz.start()}, 雑所得={misc.start()}）"
    return "判定不明"


def caveats_found(text: str) -> list[str]:
    return [p for p in CAVEAT_PHRASES if p in text]


