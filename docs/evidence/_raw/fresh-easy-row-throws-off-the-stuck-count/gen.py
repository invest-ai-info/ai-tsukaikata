def arrival_line(day: int) -> str:
    name, text, material, bad = ARRIVALS[day - 1]
    mat = "（取得できませんでした）" if bad else material
    return f"- [ ] {name}様：{text}\n  資料: {mat}"


def verify() -> None:
    lines = BASELINE.splitlines()
    done = sum(1 for l in lines if l.startswith("- [x]"))
    blocked = sum(1 for l in lines if l.startswith("- [!]"))
    pending = sum(1 for l in lines if l.startswith("- [ ]"))
    bad_baseline = BASELINE.count("（取得できませんでした）")
    print(f"ベースライン: 済{done} / 返信待ち{blocked} / 未処理{pending}（うち処理不能{bad_baseline}）")
    bad_arrivals = sum(1 for a in ARRIVALS if a[3])
    print(f"10日間の新規到着: {len(ARRIVALS)}件（うち処理不能{bad_arrivals}件 = 日{[i+1 for i,a in enumerate(ARRIVALS) if a[3]]}）")
    print(f"10日後の処理不能の累計 = ベースライン1件 + 到着{bad_arrivals}件 = {1 + bad_arrivals}件")


if __name__ == "__main__":
    verify()
