def interleave(fillers, seeds, n_chunks):
    """fillers の中に seeds を均等間隔で挿入する。"""
    out = []
    chunk = max(1, len(fillers) // n_chunks)
    si = 0
    for i, line in enumerate(fillers):
        out.append((line, None))
        if si < len(seeds) and (i + 1) % chunk == 0:
            out.append(seeds[si])
            si += 1
    while si < len(seeds):
        out.append(seeds[si])
        si += 1
    return out


